"""Score the Task 2 baselines with the Task 1 helpers (Phase 9 Task 2C).

ONNX-free / torch-free: no model runs. ``v1_greedy`` numbers are read
from the committed ``training/eval_report.json`` (no re-run); ``kn``
and ``theory`` continuations are generated by ``training/baselines.py``
and scored with ``evaluate.score_continuation`` /
``evaluate.suffix_compliance`` over the frozen 33 val records.

Run: ``python training/score_baselines.py``
Writes: ``training/baseline_scores.json``.
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import baselines as B
import evaluate as E
import tokenizer as tok


def _prefix(ids: list[int]) -> list[int]:
    cut = 1 + ((len(ids) - 1) // 2 // tok.TOKENS_PER_NOTE) * tok.TOKENS_PER_NOTE
    return ids[:max(1 + tok.TOKENS_PER_NOTE, cut)]


def _summarize(per_rec: list[dict], ids: list[str] | None = None) -> dict:
    sel = [r for r in per_rec if ids is None or r["id"] in ids]
    dec = [r for r in sel if r["decodable"]]
    suf = [r["suffix_compliance"] for r in sel
           if r["suffix_compliance"] is not None]
    return {
        "n": len(sel),
        "n_decodable": len(dec),
        "mean_compliance": (sum(r["compliance"] for r in dec) / len(dec)
                            if dec else 0.0),
        "mean_suffix": sum(suf) / len(suf) if suf else 0.0,
        "n_suffix_scored": len(suf),
    }


def _score_baseline(name: str, val: list[dict], gen) -> dict:
    per_rec = []
    for rec in val:
        prefix = _prefix(rec["ids"])
        full = gen(rec, prefix)
        s = E.score_continuation(rec, full)
        s["suffix_compliance"] = E.suffix_compliance(rec, full, len(prefix))
        per_rec.append({"id": rec["id"], "decodable": s["decodable"],
                        "compliance": s["compliance"],
                        "suffix_compliance": s["suffix_compliance"]})
    composed = [r["id"] for r in val if r["id"].startswith("composed")]
    procedural = [r["id"] for r in val if r["id"] not in composed]
    out = _summarize(per_rec)
    out["composed_only"] = _summarize(per_rec, composed)
    out["procedural_only"] = _summarize(per_rec, procedural)
    out["per-record"] = per_rec
    out["generator"] = name
    return out


def _v1_reference(report: dict) -> dict:
    per_rec = [{"id": r["id"], "decodable": r["decodable"],
                "compliance": r["compliance"],
                "suffix_compliance": r["suffix_compliance"]}
               for r in report["records"]]
    composed = [r["id"] for r in per_rec if r["id"].startswith("composed")]
    procedural = [r["id"] for r in per_rec if r["id"] not in composed]
    return {
        "generator": "v1_greedy (eval_report.json reference, no re-run)",
        "n_decodable": report["n_scored"],
        "mean_compliance": report["mean_compliance"],
        "mean_suffix": report["mean_suffix_compliance"],
        "n_suffix_scored": report["n_suffix_scored"],
        "composed_only": _summarize(per_rec, composed),
        "procedural_only": _summarize(per_rec, procedural),
        "per-record": per_rec,
    }


def main() -> int:
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="val", choices=("val", "test_locked"),
                    help="scored record set (KN trains on train.jsonl; "
                    "test_locked records are NEVER training material)")
    ap.add_argument("--out", default=None,
                    help="scores path (default baseline_scores.json for val, "
                    "baseline_scores_test_locked.json for test_locked)")
    args = ap.parse_args()
    recs = E.load_jsonl(f"{args.split}.jsonl")
    if args.split == "val":
        assert len(recs) == 33, f"frozen val must hold 33 records, got {len(recs)}"
    with open(os.path.join(HERE, "eval_report.json")) as f:
        report = json.load(f)

    kn = _score_baseline(
        "kn_continue(order=4)", recs, lambda rec, p: B.kn_continue(p, order=4))
    th = _score_baseline(
        "theory_continue", recs,
        lambda rec, p: B.theory_continue(
            p, {"tonic": rec["tonic"], "scale": rec["scale"],
                "chords": rec["chords"]}))
    scores = {"v1_greedy": _v1_reference(report), "kn": kn, "theory": th,
              "split": args.split}
    out = args.out or os.path.join(
        HERE, "baseline_scores.json" if args.split == "val"
        else "baseline_scores_test_locked.json")
    with open(out, "w") as f:
        json.dump(scores, f, indent=1)
    for k, v in scores.items():
        if not isinstance(v, dict) or "composed_only" not in v:
            continue
        c = v["composed_only"]
        print(f"{k}: mean_compliance={v['mean_compliance']:.3f} "
              f"mean_suffix={v['mean_suffix']:.3f} "
              f"composed[n={c['n']}] comp={c['mean_compliance']:.3f} "
              f"suffix={c['mean_suffix']:.3f} (scored={c['n_suffix_scored']}) "
              f"decodable={v.get('n_decodable', '?')}")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
