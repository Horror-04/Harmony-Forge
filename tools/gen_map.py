"""Agent navigation map: one line per code file + its public symbols.

Scans src/ (.h/.hpp/.cpp), tools/ + tests/ + training/ (.py, .cpp under
tests/) and writes docs/MAP.md. Deny-paths (JUCE/, external/, *.onnx,
training/corpus/sealed_test.jsonl, build*/) are never scanned.

Environment/package trees are pruned from the walk as well: a directory whose
name starts with `.venv` (or that is named `venv`, `__pycache__`,
`.pytest_cache`, `node_modules`, `.git`) is never descended into. The venv
trees under training/ hold tens of thousands of site-packages `.py` files
that are not repo code, and scanning them made the map both enormous and
machine-specific.

Symbol rule (best-effort, deterministic, single-line only):
- C++: `namespace` / `class` / `struct` / `enum [class]` names +
  TEST_CASE("name") suite names.
- Python: top-level `def` / `class` names.

Usage:
  py -3 tools/gen_map.py           # regenerate docs/MAP.md (LF, sorted)
  py -3 tools/gen_map.py --check   # exit 1 if docs/MAP.md is stale, else 0

The flag is parsed by argparse, so an UNKNOWN argument (a typo such as
``--chek``, or ``--check=1``) is a usage ERROR (exit 2) instead of a silent
fall-through to the WRITE path: a mistyped check must never rewrite the
file it was meant to verify.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(_HERE)
_MAP = os.path.join(_REPO, "docs", "MAP.md")

MAX_SYMS = 30

_CPP_EXTS = (".h", ".hpp", ".cpp")
_PY_EXTS = (".py",)

# Directory names that are never descended into (environment / package
# noise, not repo code). `.venv*` is matched by prefix so every venv
# flavour (.venv, .venv-cuda, ...) is covered.
_SKIP_DIRS = ("venv", "__pycache__", ".pytest_cache", "node_modules", ".git")


def _skip_dir(name: str) -> bool:
    """True for directories the map never walks into."""
    return name in _SKIP_DIRS or name.startswith(".venv")

_NS_RE = re.compile(r"^\s*namespace\s+(\w+)")
_CLASS_RE = re.compile(r"^\s*(?:class|struct)\s+(\w+)")
_ENUM_RE = re.compile(r"^\s*enum\s+(?:class\s+)?(\w+)")
_CASE_RE = re.compile(r'^\s*TEST_CASE\s*\(\s*"([^"]+)"')
_PY_DEF_RE = re.compile(r"^(?:def|class)\s+(\w+)")


def _code_lines(path: str) -> list[str]:
    with open(path, encoding="utf8", errors="replace") as f:
        return f.read().splitlines()


def symbols_of(rel: str, lines: list[str]) -> list[str]:
    syms: list[str] = []
    if rel.endswith(_CPP_EXTS):
        for ln in lines:
            m = _CASE_RE.match(ln)
            if m:
                syms.append("case:" + m.group(1))
                continue
            m = _NS_RE.match(ln)
            if m:
                syms.append("ns:" + m.group(1))
                continue
            m = _CLASS_RE.match(ln)
            if m and m.group(1) not in ("return", "const"):
                syms.append(m.group(1))
                continue
            m = _ENUM_RE.match(ln)
            if m:
                syms.append(m.group(1))
    elif rel.endswith(_PY_EXTS):
        for ln in lines:
            m = _PY_DEF_RE.match(ln)
            if m:
                syms.append(m.group(1))
    # Order-preserving dedup; truncate for readability (count kept exact).
    seen: list[str] = []
    for s in syms:
        if s not in seen:
            seen.append(s)
    return seen


def iter_files() -> list[str]:
    roots = ("src", "tools", "tests", "training")
    out: list[str] = []
    for root in roots:
        base = os.path.join(_REPO, *root.split("/"))
        for dp, dns, fns in os.walk(base):
            # Prune environment/package trees in place (os.walk honours the
            # in-place edit of `dirs`): they hold no repo code.
            dns[:] = [d for d in dns if not _skip_dir(d)]
            for fn in sorted(fns):
                if fn.endswith(_CPP_EXTS) or fn.endswith(_PY_EXTS):
                    full = os.path.join(dp, fn)
                    rel = os.path.relpath(full, _REPO).replace(os.sep, "/")
                    if rel.endswith(".onnx"):
                        continue
                    if rel == "training/corpus/sealed_test.jsonl":
                        continue
                    out.append(rel)
    return sorted(out)


def render() -> str:
    files = iter_files()
    total_syms = 0
    body: list[str] = []
    for rel in files:
        syms = symbols_of(rel, _code_lines(os.path.join(_REPO, *rel.split("/"))))
        total_syms += len(syms)
        shown = syms[:MAX_SYMS]
        extra = "" if len(syms) <= MAX_SYMS else " (+%d more)" % (len(syms) - MAX_SYMS)
        body.append("- `%s` — %s%s" % (rel, ", ".join("`%s`" % s for s in shown), extra))
    head = [
        "# MAP: file -> one line + public symbols",
        "",
        "<!-- GENERATED by `py -3 tools/gen_map.py`; do not edit by hand. -->",
        "<!-- Verify with `py -3 tools/gen_map.py --check`. Deny-paths "
        "(JUCE/, external/, *.onnx, training/corpus/sealed_test.jsonl, "
        "build*/) are never scanned; environment/package dirs (.venv*, "
        "venv, __pycache__, .pytest_cache, node_modules, .git) are pruned; "
        "see docs/AGENT_PERMISSIONS.md. -->",
        "",
        "Files: %d, symbols: %d." % (len(files), total_syms),
        "",
    ]
    return "\n".join(head + body) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify docs/MAP.md is FRESH; never writes (exit 1 "
                         "when stale)")
    args = ap.parse_args(sys.argv[1:] if argv is None else argv)
    text = render()
    if args.check:
        try:
            with open(_MAP, encoding="utf8", newline="") as f:
                current = f.read()
        except OSError:
            current = ""
        if current != text:
            print("gen_map: STALE docs/MAP.md "
                  "(run `py -3 tools/gen_map.py` to regenerate)")
            return 1
        print("gen_map: FRESH (%d bytes)" % len(text.encode("utf8")))
        return 0
    with open(_MAP, "w", encoding="utf8", newline="\n") as f:
        f.write(text)
    print("gen_map: wrote docs/MAP.md (%d bytes)" % len(text.encode("utf8")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
